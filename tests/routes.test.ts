import { afterEach, describe, expect, it, vi } from 'vitest'
import { readFileSync } from 'node:fs'
const captureTime = Date.parse('2026-11-06T05:00:00Z')
const fixture = (name: string) => readFileSync(new URL(`./fixtures/official-feed/${name}`, import.meta.url), 'utf8')
afterEach(() => { vi.restoreAllMocks(); vi.unstubAllGlobals(); vi.unstubAllEnvs(); vi.resetModules() })

describe('Next.js Node route handlers', () => {
  it('serves validated fixtures and shares the warm cache across national and local requests', async () => {
    vi.spyOn(Date, 'now').mockReturnValue(captureTime)
    vi.stubEnv('RESULTS_PUBLICATION_CONFIRMED', '')
    const fetcher = vi.fn(async (url: string) => new Response(fixture(url.endsWith('/e01/e01.xml') ? 'e01.xml' : url.split('/').at(-1)!)))
    vi.stubGlobal('fetch', fetcher)
    const national = await import('../app/api/results/route')
    const local = await import('../app/api/electorates/[id]/route')
    const first = await national.GET()
    expect(first.status).toBe(200)
    expect(first.headers.get('cache-control')).toContain('s-maxage=30')
    const body = await first.json()
    expect(body.status).toBe('waiting'); expect(body.results).toBeNull()
    expect(body.electorates).toHaveLength(71)
    expect(Number.isFinite(Date.parse(body.fetchedAt))).toBe(true)
    await national.GET()
    expect(fetcher).toHaveBeenCalledTimes(5)
    const response = await local.GET(new Request('http://localhost/api/electorates/1'), { params: Promise.resolve({ id: '1' }) })
    expect(response.status).toBe(200)
    expect((await response.json()).electorateId).toBe('1')
    expect(fetcher).toHaveBeenCalledTimes(6)
  })
  it('fails closed on malformed upstream data and rejects invalid IDs before fetching', async () => {
    const fetcher = vi.fn(async () => new Response('<html>Not XML</html>'))
    vi.stubGlobal('fetch', fetcher)
    const national = await import('../app/api/results/route')
    const local = await import('../app/api/electorates/[id]/route')
    const invalid = await local.GET(new Request('http://localhost/api/electorates/0'), { params: Promise.resolve({ id: '0' }) })
    expect(invalid.status).toBe(400); expect(fetcher).not.toHaveBeenCalled()
    const failed = await national.GET()
    expect(failed.status).toBe(503)
    expect(failed.headers.get('cache-control')).toBe('no-store')
    expect((await failed.json()).status).toBe('unavailable')
  })
})
